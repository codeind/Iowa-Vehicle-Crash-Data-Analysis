"""Build dashboard/dashboard_data.js from the public Iowa DOT crash file.

Download "Vehicle Crashes in Iowa" (CSV) from
https://data.iowa.gov/Crashes/Vehicle-Crashes-in-Iowa/tw78-ziwj and run:
    python dashboard/build_data.py path/to/Vehicle_Crashes_in_Iowa.csv
"""
import json
import sys
from pathlib import Path

import pandas as pd

SEVERITY = ["Fatal", "Major Injury", "Minor Injury", "Possible/Unknown", "Property Damage Only"]
cols = ["Date of Crash", "Day of Week", "Hour", "County Name", "Crash Severity", "Weather Conditions",
        "Surface Conditions", "Light Conditions", "Major Cause", "Drug or Alcohol ", "Number of Fatalities",
        "Number of Injuries", "Number of Major Injuries"]
df = pd.read_csv(sys.argv[1], usecols=cols, low_memory=False)
df = df.rename(columns={"Drug or Alcohol ": "Drug or Alcohol"})
df["Date"] = pd.to_datetime(df["Date of Crash"], format="%m/%d/%Y", errors="coerce")
df = df.dropna(subset=["Date"])
df["Year"] = df["Date"].dt.year
df["Month"] = df["Date"].dt.month
df["HourNum"] = pd.to_numeric(df["Hour"].str[:2], errors="coerce")
df["Dow"] = pd.to_numeric(df["Day of Week"].str[0], errors="coerce")       # 1 = Sunday
df["Severity"] = df["Crash Severity"].fillna("Unknown")
df["Fatal"] = df["Severity"].eq("Fatal")
df["Serious"] = df["Severity"].isin(["Fatal", "Major Injury"])
years = sorted(df["Year"].unique())
last_full_year = int(df.loc[df["Month"] == 12, "Year"].max())


def top(series, n, label_other=True):
    counts = series.fillna("Not reported").value_counts()
    out = counts.head(n)
    if label_other and len(counts) > n:
        out = pd.concat([out, pd.Series({"All other": counts.iloc[n:].sum()})])
    return out


def tidy(label):
    label = str(label)
    if label.startswith("Other (explain"):
        return "Other"
    if label.startswith("FTYROW:"):
        return "Failed to yield: " + label.split(":", 1)[1].strip().lower()
    if label.startswith("Driver Distraction:"):
        return "Distraction: " + label.split(":", 1)[1].strip().lower()
    if label.startswith("Operating vehicle in an reckless"):
        return "Reckless or careless driving"
    return label


def rate_table(col, n):
    g = df.groupby(df[col].fillna("Not reported").map(tidy)).agg(crashes=("Severity", "size"), serious=("Serious", "sum"), fatal=("Fatal", "sum"))
    g = g[g["crashes"] >= 500].sort_values("crashes", ascending=False).head(n)
    return [{"k": k, "crashes": int(r.crashes), "serious_rate": round(float(r.serious / r.crashes * 100), 2),
             "fatal": int(r.fatal)} for k, r in g.iterrows()]


by_year = df.groupby("Year").agg(crashes=("Severity", "size"), fatal_crashes=("Fatal", "sum"),
                                 deaths=("Number of Fatalities", "sum"), injuries=("Number of Injuries", "sum"))
heat = df.dropna(subset=["Dow", "HourNum"]).groupby(["Dow", "HourNum"]).size()
heat_grid = [[int(heat.get((d, h), 0)) for h in range(24)] for d in range(1, 8)]
sev = df["Severity"].value_counts()
counties = df.groupby("County Name").agg(crashes=("Severity", "size"), fatal=("Fatal", "sum"), serious=("Serious", "sum"))
counties = counties.sort_values("crashes", ascending=False)
impaired = df["Drug or Alcohol"].fillna("Not reported")
# alcohol or drugs indicated (excludes "None Indicated" and "Refused")
impaired_flag = ~impaired.isin(["None Indicated", "Not reported", "Refused"])

data = {
    "range": [df["Date"].min().strftime("%b %Y"), df["Date"].max().strftime("%b %Y")],
    "summary": {
        "crashes": int(len(df)),
        "deaths": int(df["Number of Fatalities"].sum()),
        "fatal_crashes": int(df["Fatal"].sum()),
        "injuries": int(df["Number of Injuries"].sum()),
        "last_full_year": last_full_year,
        "impaired_share_of_fatal": round(float(impaired_flag[df["Fatal"]].mean() * 100), 1),
        "impaired_share_all": round(float(impaired_flag.mean() * 100), 1),
    },
    "years": [int(y) for y in by_year.index],
    "by_year": {k: [int(v) for v in by_year[k].values] for k in by_year.columns},
    "heat": heat_grid,
    "severity": [[s, int(sev.get(s, 0))] for s in SEVERITY],
    "weather": rate_table("Weather Conditions", 8),
    "surface": rate_table("Surface Conditions", 7),
    "light": rate_table("Light Conditions", 6),
    "causes": rate_table("Major Cause", 12),
    "counties": [{"k": k.title(), "crashes": int(r.crashes), "fatal": int(r.fatal),
                  "serious_rate": round(float(r.serious / r.crashes * 100), 2)} for k, r in counties.iterrows()],
    "month_profile": [int(x) for x in df.groupby("Month").size().reindex(range(1, 13)).values],
}
out = Path(__file__).with_name("dashboard_data.js")
out.write_text("// Generated by dashboard/build_data.py from the Iowa DOT crash file - do not edit by hand.\n"
               "window.CRASH = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {out.name} ({out.stat().st_size/1e3:.0f} KB)")
print(json.dumps(data["summary"]), data["range"], "years", data["years"][0], "-", data["years"][-1])
print("severity", data["severity"])
print("weather", data["weather"][:4]); print("causes", data["causes"][:4]); print("top counties", data["counties"][:3])
